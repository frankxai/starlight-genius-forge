#!/usr/bin/env python3
"""Starlight Idea Swarm — local intake skeleton.

Writes a dated Idea card under docs/ideas/ and an optional GitHub issue body
stub under docs/ideas/_outbox/. No network calls. Safe under BOUNDED disk.

Usage:
  python scripts/idea_swarm_intake.py --text "Your idea..." --source hermes --tags "arcanea,product"
  python scripts/idea_swarm_intake.py --file path/to/note.md --source chatgpt-paste
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from uuid import uuid4


ROOT = Path(__file__).resolve().parents[1]
IDEAS = ROOT / "docs" / "ideas"
OUTBOX = IDEAS / "_outbox"


def slugify(text: str, max_len: int = 48) -> str:
    s = text.strip().lower()
    s = re.sub(r"[^a-z0-9\s-]", "", s)
    s = re.sub(r"[\s_]+", "-", s).strip("-")
    return (s[:max_len] or "idea").rstrip("-")


def build_card(
    text: str,
    source: str,
    tags: list[str],
    idea_id: str,
    created: str,
) -> str:
    one_liner = text.strip().splitlines()[0][:160]
    tag_line = ", ".join(tags) if tags else "untagged"
    return f"""# Idea Card — {idea_id}

| Field | Value |
|-------|-------|
| id | `{idea_id}` |
| created | {created} |
| source | {source} |
| tags | {tag_line} |
| stage | capture |
| ship_bar | _pending quantify_ |
| critic | _pending debate_ |

## One-liner

{one_liner}

## Raw

{text}

## Provenance

- Intake: `scripts/idea_swarm_intake.py`
- Doctrine: `docs/IDEA-SWARM.md`
- Next: Cluster → Refine → Quantify → Debate (Planner/Executor/Critic) → Align (GitHub)

## Alignment stubs

- [ ] Map to portfolio repo / ROADMAP
- [ ] Open GitHub issue with label `idea-swarm`
- [ ] Link second-brain vault note if from export

## Debate receipt

```json
{{
  "ideaId": "{idea_id}",
  "stage": "capture",
  "critic": {{"verdict": "PENDING", "blockers": [], "score": null}}
}}
```
"""


def build_issue_body(idea_id: str, text: str, tags: list[str]) -> str:
    tag_line = ", ".join(f"`{t}`" for t in tags) if tags else "_none_"
    return f"""## Idea Swarm capture

**ID:** `{idea_id}`  
**Tags:** {tag_line}

### Summary

{text.strip()[:2000]}

### Done when

- [ ] Critic PASS on refine + quantify
- [ ] Linked to roadmap or explicit new goal
- [ ] Evidence path in queen report or vault

### Labels

`idea-swarm` · add `roadmap-align:<repo>` when known

---
_Generated by Starlight Idea Swarm intake. Not auto-filed until Critic PASS._
"""


def write_new(path: Path, text: str) -> None:
    # Publish a complete file atomically without replacing another capture.
    temp = path.with_name(path.name + "." + uuid4().hex + ".tmp")
    owned = False
    try:
        with temp.open("x", encoding="utf-8", newline="\n") as stream:
            owned = True
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.link(temp, path)
    finally:
        if owned:
            temp.unlink(missing_ok=True)


def complete_capture(meta: dict) -> tuple[Path, Path, Path]:
    idea_id = meta.get("ideaId")
    if not isinstance(idea_id, str) or not re.fullmatch(r"isw-\d{8}-[a-z0-9-]+-[a-f0-9]{32}", idea_id):
        raise ValueError("Invalid recovery capture identifier")
    text = meta.get("rawText")
    if not isinstance(text, str) or not text.strip():
        raise ValueError("Invalid recovery original text")
    if hashlib.sha256(text.encode("utf-8")).hexdigest() != meta.get("rawTextSha256"):
        raise ValueError("Recovery original text hash mismatch")
    if not isinstance(meta.get("source"), str) or not isinstance(meta.get("created"), str):
        raise ValueError("Invalid recovery provenance")
    tags = meta.get("tags")
    if not isinstance(tags, list) or any(not isinstance(tag, str) for tag in tags):
        raise ValueError("Invalid recovery tags")
    if meta.get("sourceRef") is not None and not isinstance(meta["sourceRef"], str):
        raise ValueError("Invalid recovery source locator")
    if "rawTags" in meta or "rawTagsSha256" in meta:
        raw_tags = meta.get("rawTags")
        if not isinstance(raw_tags, str) or hashlib.sha256(raw_tags.encode("utf-8")).hexdigest() != meta.get("rawTagsSha256"):
            raise ValueError("Recovery original tags hash mismatch")
        if [tag.strip() for tag in raw_tags.split(",") if tag.strip()] != tags:
            raise ValueError("Recovery normalized tags mismatch")
    card = IDEAS / f"{idea_id}.md"
    issue = OUTBOX / f"{idea_id}-github-issue.md"
    final = OUTBOX / f"{idea_id}.json"
    if meta.get("cardPath") != card.relative_to(ROOT).as_posix() or meta.get("issueBodyPath") != issue.relative_to(ROOT).as_posix() or meta.get("stage") != "capture":
        raise ValueError("Recovery paths or stage mismatch")
    outputs = [(card, build_card(text, meta["source"], tags, idea_id, meta["created"])),
               (issue, build_issue_body(idea_id, text, tags)),
               (final, json.dumps(meta, indent=2) + "\n")]
    # Detect conflicts in all destinations before extending a partial capture.
    for path, content in outputs:
        if path.exists() and path.read_bytes() != content.encode("utf-8"):
            raise FileExistsError(f"Recovery conflict; preserved {path.name}")
    for path, content in outputs:
        if not path.exists():
            try:
                write_new(path, content)
            except FileExistsError:
                if path.read_bytes() != content.encode("utf-8"):
                    raise
        if path.read_bytes() != content.encode("utf-8"):
            raise OSError("Capture readback mismatch")
    return card, issue, final


def unique_json_fields(pairs: list[tuple[str, object]]) -> dict:
    """Reject ambiguous source/provenance values before any capture write."""
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate JSON field")
        result[key] = value
    return result


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Starlight Idea Swarm intake")
    p.add_argument("--packet", help="Import a private version-1 cockpit capture packet")
    p.add_argument("--text", type=str, help="Raw idea text")
    p.add_argument("--file", type=str, help="Read idea text from file")
    p.add_argument("--source", type=str, default="hermes", help="Provenance source")
    p.add_argument("--tags", type=str, default="", help="Comma-separated tags")
    p.add_argument("--source-ref", type=str, help="Original source locator; supplied attribution is not verified")
    p.add_argument("--recover-id", help="Recover an existing private pending capture; never overwrites different bytes")
    args = p.parse_args(argv)

    if args.recover_id:
        if args.packet is not None or args.text is not None or args.file is not None or args.source_ref is not None or args.tags or args.source != "hermes":
            p.error("Recovery cannot be combined with new capture input")
        if not re.fullmatch(r"isw-\d{8}-[a-z0-9-]+-[a-f0-9]{32}", args.recover_id):
            p.error("Invalid recovery identifier")
        journal = OUTBOX / "_pending" / f"{args.recover_id}.json"
        try:
            meta = json.loads(journal.read_bytes(), object_pairs_hook=unique_json_fields)
            if not isinstance(meta, dict):
                raise ValueError("Invalid recovery journal")
        except (OSError, UnicodeError, ValueError) as error:
            print(f"Cannot read recovery journal: {error}", file=sys.stderr)
            return 2
        try:
            if meta.get("ideaId") != args.recover_id:
                raise ValueError("Recovery journal identity mismatch")
            paths = complete_capture(meta)
        except (OSError, ValueError) as error:
            print(f"Cannot recover capture: {error}", file=sys.stderr)
            return 2
        print(f"ideaId={args.recover_id}")
        print(f"card={paths[0]}\nissue_body={paths[1]}\nmeta={paths[2]}")
        return 0

    if args.packet is not None:
        if args.text is not None or args.file is not None or args.source_ref is not None or args.tags or args.source != "hermes":
            p.error("Packet import cannot be combined with other capture input")
        try:
            packet = json.loads(Path(args.packet).read_bytes().decode("utf-8"), object_pairs_hook=unique_json_fields)
            if not isinstance(packet, dict) or set(packet) != {"version", "rawText", "tags", "source", "sourceRef"}:
                raise ValueError("Unexpected packet fields")
            if type(packet["version"]) is not int or packet["version"] != 1:
                raise ValueError("Unsupported packet version")
            if not all(isinstance(packet[key], str) for key in ("rawText", "tags", "source")) or not packet["source"].strip():
                raise ValueError("Invalid packet text or provenance")
            packet["rawText"].encode("utf-8")
            if packet["sourceRef"] is not None and not isinstance(packet["sourceRef"], str):
                raise ValueError("Invalid packet source locator")
            text, args.tags, args.source, args.source_ref = (packet[key] for key in ("rawText", "tags", "source", "sourceRef"))
        except (OSError, UnicodeError, ValueError) as error:
            print(f"Cannot import capture packet: {error}", file=sys.stderr)
            return 2
    elif args.file:
        text = Path(args.file).read_bytes().decode("utf-8")
    elif args.text:
        text = args.text
    else:
        print("Provide --text, --file or --packet", file=sys.stderr)
        return 2

    if args.source_ref is not None and not args.source_ref.strip():
        print("Source locator cannot be blank", file=sys.stderr)
        return 2

    if not text.strip():
        print("Empty idea text", file=sys.stderr)
        return 2

    raw_tags = args.tags
    try:
        raw_tags_sha256 = hashlib.sha256(raw_tags.encode("utf-8")).hexdigest()
    except UnicodeError:
        print("Original tags cannot be encoded as UTF-8", file=sys.stderr)
        return 2
    tags = [t.strip() for t in raw_tags.split(",") if t.strip()]
    now = datetime.now(timezone.utc)
    created = now.strftime("%Y-%m-%dT%H:%M:%SZ")
    day = now.strftime("%Y%m%d")
    idea_id = f"isw-{day}-{slugify(text)}-{uuid4().hex}"

    IDEAS.mkdir(parents=True, exist_ok=True)
    OUTBOX.mkdir(parents=True, exist_ok=True)

    card_path = IDEAS / f"{idea_id}.md"
    issue_path = OUTBOX / f"{idea_id}-github-issue.md"
    meta_path = OUTBOX / f"{idea_id}.json"

    if any(path.exists() for path in (card_path, issue_path, meta_path)):
        print("Capture path already exists; existing files were preserved.", file=sys.stderr)
        return 2

    meta = {
                "ideaId": idea_id,
                "created": created,
                "source": args.source,
                "sourceRef": args.source_ref,
                "rawText": text,
                "rawTextSha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
                "tags": tags,
                "rawTags": raw_tags,
                "rawTagsSha256": raw_tags_sha256,
                "cardPath": str(card_path.relative_to(ROOT)).replace("\\", "/"),
                "issueBodyPath": str(issue_path.relative_to(ROOT)).replace("\\", "/"),
                "stage": "capture",
            }
    pending = OUTBOX / "_pending"
    pending.mkdir(exist_ok=True)
    journal = pending / f"{idea_id}.json"
    # The journal stays private and retained for repeat recovery and provenance.
    write_new(journal, json.dumps(meta, indent=2) + "\n")
    print(f"recover_id={idea_id}", flush=True)
    complete_capture(meta)

    print(f"ideaId={idea_id}")
    print(f"card={card_path}")
    print(f"issue_body={issue_path}")
    print(f"meta={meta_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
